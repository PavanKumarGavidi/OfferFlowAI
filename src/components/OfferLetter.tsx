export function OfferLetterModal({ candidate, open, onClose }: { candidate: Candidate | null; open: boolean; onClose: () => void }) {
  const { db } = useStore();
  const company = candidate ? db.companies.find((c) => c.id === candidate.companyId) : null;
  if (!candidate || !company) return null;
  return (
    <Modal open={open} onClose={onClose} title={`Offer Letter — ${candidate.offer?.number ?? ""}`} subtitle={`${candidate.name} · ${candidate.position}`} width="max-w-3xl"
      footer={
        <>
          <Button variant="outline" icon={<Printer size={15} />} onClick={() => window.print()}>Download PDF</Button>
          <Button icon={<Check size={15} />} onClick={onClose}>Done</Button>
        </>
      }
    >
      <div className="print-root bg-ink-100/60 dark:bg-ink-925 rounded-xl p-3 sm:p-5 -m-1">
        <OfferPaper company={company} candidate={candidate} />
      </div>
    </Modal>
  );
}

