const TRACK_STEPS: { key: string; label: string; date: (o: Offer) => string | undefined }[] = [
  { key: "generated", label: "Generated", date: (o) => o.generatedAt },
  { key: "sent", label: "Sent", date: (o) => o.sentAt },
  { key: "viewed", label: "Viewed", date: (o) => o.viewedAt },
];

export function OfferTrack({ offer }: { offer: Offer }) {
  const reached = (key: string) => {
    const order = ["generated", "sent", "viewed", "accepted", "rejected"];
    if (offer.status === "rejected" && key === "viewed") return !!offer.viewedAt;
    return order.indexOf(offer.status) >= order.indexOf(key);
  };
  return (
    <div className="flex items-center gap-1.5 flex-wrap">
      {TRACK_STEPS.map((s, i) => {
        const on = reached(s.key);
        return (
          <span key={s.key} className="flex items-center gap-1.5">
            {i > 0 && <span className={`w-4 h-px ${on ? "bg-cobalt-400" : "bg-ink-300/60 dark:bg-white/15"}`} />}
            <span className={`inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[11px] font-bold ring-1 ring-inset ${on ? "bg-cobalt-500/10 text-cobalt-700 dark:text-cobalt-300 ring-cobalt-500/25" : "bg-ink-900/4 dark:bg-white/5 text-ink-400 ring-ink-900/10 dark:ring-white/10"}`}>
              {on && <Check size={11} />}
              {s.label}
            </span>
          </span>
        );
      })}
      {offer.status === "accepted" && <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[11px] font-bold bg-emerald-500/10 text-emerald-700 dark:text-emerald-300 ring-1 ring-inset ring-emerald-500/25"><Check size={11} /> Accepted {fmtDate(offer.respondedAt)}</span>}
      {offer.status === "rejected" && <span className="px-2 py-0.5 rounded-full text-[11px] font-bold bg-rose-500/10 text-rose-700 dark:text-rose-300 ring-1 ring-inset ring-rose-500/25">Rejected {fmtDate(offer.respondedAt)}</span>}
    </div>
  );
}
